"""Streamlit app: Esha Ishaq's digital clone (hybrid BM25 + dense RAG, answers from Gemini).

Runs on Streamlit Community Cloud. The Gemini key is read from Streamlit secrets
(GEMINI_API_KEY), never from the code.
"""
from __future__ import annotations

import html
import os
import re

import streamlit as st
from streamlit.errors import StreamlitSecretNotFoundError

from rag import MODES, RRF_K, load_retriever

NOT_IN_NOTES = "I don't have that in my notes."
MIN_DENSE, MIN_BM25 = 0.20, 2.0  # below both, nothing in the notes is about the question
PRIVATE = re.compile(r"\b(phone|mobile|contact number|address|cnic|passport|password|bank|account no|"
                     r"roll ?no|id card|email)\b", re.I)

st.set_page_config(page_title="Esha Ishaq · AI Clone", page_icon="🔎", layout="wide")

# Streamlit exposes root-level secrets as environment variables; make sure llm.py sees the key.
try:
    if "GEMINI_API_KEY" in st.secrets:
        os.environ["GEMINI_API_KEY"] = st.secrets["GEMINI_API_KEY"]
except StreamlitSecretNotFoundError:  # no secrets file (local run): fall back to the environment
    pass

from llm import generate_gemini, is_grounded, clean  # noqa: E402  (after the key is in the env)


@st.cache_resource(show_spinner="Loading my notes and the embedding model…")
def get_retriever():
    return load_retriever()


retriever = get_retriever()

st.markdown(
    "<div style='border:2px solid #d39e00;background:#fff8e1;color:#7a4f01;border-radius:10px;"
    "padding:10px 14px;font-weight:600;text-align:center'>⚠️ This is an AI clone, not the real person. "
    "It answers only from Esha Ishaq's own notes and can make mistakes.</div>",
    unsafe_allow_html=True,
)
st.title("🤖 Chat with Esha's digital clone")
st.caption("BS Computer Science (7th semester), UMT Sialkot · web dev, cybersecurity & digital forensics. "
           "Ask about my studies, projects, skills, hobbies or opinions.")

EXAMPLES = [
    "What is LoopTech360 Support?",
    "What does the best.pt file do in your project?",
    "What would you tell a fresher joining computer science?",
    "How do you usually get ready for your exams?",
    "Which subject puts you to sleep in class?",
    "What is your favourite football club?",
    "Are you the real Esha?",
]

left, right = st.columns([3, 2], gap="large")
with left:
    with st.form("ask"):
        question = st.text_area("Your question", key="question", height=80,
                                placeholder="e.g. What projects have you built?")
        c1, c2 = st.columns([3, 2])
        mode = c1.radio("Retrieval mode", MODES, horizontal=True)
        k = c2.slider("Top-k chunks", 3, 6, 3)
        submitted = st.form_submit_button("Ask Esha's clone", type="primary")
with right:
    st.markdown("**Try an example**")
    for ex in EXAMPLES:
        if st.button(ex, key=f"ex-{ex}", use_container_width=True):
            st.session_state["pending"] = ex
            st.rerun()

if st.session_state.get("pending"):
    question, submitted = st.session_state.pop("pending"), True

if submitted and question.strip():
    question = question.strip()
    hits = retriever.search(question, mode, k)
    contexts = [f"({h.chunk.source}) {h.chunk.text}" for h in hits]

    with left:
        st.subheader("Answer")
        box, by = st.empty(), st.empty()
        best_dense = max(h.dense_score for h in retriever.search(question, "Dense only", 1))
        best_bm25 = max(h.bm25_score for h in retriever.search(question, "BM25 only", 1))
        if PRIVATE.search(question):
            box.info("Sorry, I don't share private details like phone numbers, addresses, ID numbers or "
                     "account details. 🙂")
            by.caption("Generated by: privacy rule (no LLM call)")
        elif best_dense < MIN_DENSE and best_bm25 < MIN_BM25:
            box.info(NOT_IN_NOTES)
            by.caption(f"Generated by: out of scope (best cosine {best_dense:.2f}, best BM25 {best_bm25:.2f}), no LLM call")
        else:
            text, label = "", ""
            try:
                for text, label in generate_gemini(question, contexts):
                    box.info(clean(text) or "…")
                final = clean(text) or NOT_IN_NOTES
                if is_grounded(final, contexts):
                    box.info(final)
                    by.caption(f"Generated by: {label}")
                else:
                    box.info(NOT_IN_NOTES)
                    by.caption(f"Generated by: {label} · grounding check rejected an unsupported answer")
            except Exception as exc:  # shown to the visitor instead of a stack trace
                box.error(f"The language model failed: {exc}")

    with right:
        st.markdown("**Same question, all three modes (top-k chunk IDs)**")
        cols = {m: [h.chunk.chunk_id for h in retriever.search(question, m, k)] for m in MODES}
        st.table({"Rank": list(range(1, k + 1)), **cols})

    st.subheader("Retrieved chunks (source, chunk ID and scores)")
    score_name = {"BM25 only": "BM25 score", "Dense only": "cosine similarity"}.get(mode, f"RRF score (k={RRF_K})")
    for i, h in enumerate(hits, 1):
        c = h.chunk
        with st.container(border=True):
            st.markdown(f"**#{i} · {c.chunk_id}** · source: `{c.source}` · section: *{html.escape(c.section)}*")
            st.caption(f"{score_name}: **{h.score:.4f}** | BM25 {h.bm25_score:.2f} (rank {h.bm25_rank}) | "
                       f"dense {h.dense_score:.3f} (rank {h.dense_rank})")
            with st.expander("show chunk text"):
                st.write(c.text)

st.divider()
st.caption("Pipeline: 8 first-person notes → 25 chunks (~250 words, 40-word overlap) → BM25 (rank_bm25) + "
           "dense (all-MiniLM-L6-v2, precomputed embeddings.npy) → Reciprocal Rank Fusion → Gemini answers in "
           "first person from the retrieved chunks only. Code: huggingface.co/spaces/bhonduu/esha-ishaq-digital-clone")
